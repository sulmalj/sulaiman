  'تُكتب مدًّا (آ)؛ لأن الهمزة مفتوحة، وقبلها فتحة، ثم جاء بعدها ألف، فاجتمعت صورتان ألفيتان في اللفظ والرسم، فدُمجتا في صورة واحدة هي (آ) تخفيفًا واختصارًا.'
